#!/usr/bin/env node
// Generates docs/contributing/good-first-units.md from `plans/tools/corpus.mjs catalog --json`.
// Status is deliberately NOT used or printed: the orchestrator flips it all night, and
// including it would make --check drift. Claimers check the unit file's status line.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'docs/contributing/good-first-units.md');
const CAP = 10;
// Data-only units for domain experts and non-programmers who can read law (W13). Forced in.
const FORCED = ['13-u18', '10-u67'];

const cat = JSON.parse(execFileSync('node', [join(root, 'plans/tools/corpus.mjs'), 'catalog', '--json'], { cwd: root, encoding: 'utf8', maxBuffer: 1 << 28 }));
const tagged = (u, t) => (u.tags || []).includes(t);
const ok = (u) => !tagged(u, 'needs-context') && (tagged(u, 'good-first') || FORCED.includes(u.id) ||
  (!u.founder_gate && !(u.needs || []).length && u.est_hours <= 1));
const forced = (u) => tagged(u, 'good-first') || FORCED.includes(u.id);
const rows = cat.filter(ok)
  .sort((a, b) => forced(b) - forced(a) || a.priority - b.priority || a.id.localeCompare(b.id))
  .slice(0, CAP);

const esc = (s) => String(s).replace(/\|/g, '\\|');
const lines = [
  '# Good first units',
  '',
  'Generated by `node scripts/sync-good-first.mjs`. Do not edit by hand. How units are chosen and how to claim one: [README](README.md).',
  '',
  'This list does not show progress. Open the unit file and read its `status` line before you claim it.',
  '',
];
if (rows.length < 3) {
  lines.push('Fewer than three units qualify right now. Another way in: the [open questions register](../open-questions/), where community answers are welcome.', '');
}
lines.push('| Unit | Title | Repo | Area | Hours | Context | How to claim |', '|---|---|---|---|---|---|---|');
for (const u of rows) {
  const ctx = [`[unit](../../${u.path})`, ...(u.spec || []).slice(0, 2).map((s) => `[${s.split('/').pop().split('#')[0]}](../../${s.split('#')[0]})`)].join(', ');
  lines.push(`| ${u.id} | ${esc(u.title)} | ${u.repo} | ${u.area} | ${u.est_hours} | ${ctx} | Open an issue citing ${u.id} |`);
}
const text = lines.join('\n') + '\n';
if (Buffer.byteLength(text) > 25 * 1024) { console.error('index exceeds 25 KB'); process.exit(1); }

if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== text) {
    console.error('docs/contributing/good-first-units.md is stale: run `node scripts/sync-good-first.mjs` and commit it.');
    process.exit(1);
  }
  console.log('good-first index up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${rows.length} rows`);
}
